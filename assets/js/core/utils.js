  /**
   * Format numbers to Nepali / South Asian Currency (NPR Rs. ##,##,###)
   * @param {number|string} amount
   * @param {boolean} showSymbol
   * @returns {string}
   */
  formatCurrency(amount, showSymbol = true) {
    if (amount === null || amount === undefined || isNaN(amount)) {
      return showSymbol ? "Rs. 0" : "0";
    }
    const num = Math.round(Number(amount));
    const isNegative = num < 0;
    const absStr = Math.abs(num).toString();

    let result = "";
    if (absStr.length <= 3) {
      result = absStr;
    } else {
      const lastThree = absStr.substring(absStr.length - 3);
      const remaining = absStr.substring(0, absStr.length - 3);
      const parts = [];
      for (let i = remaining.length; i > 0; i -= 2) {
        const start = Math.max(0, i - 2);
        parts.unshift(remaining.substring(start, i));
      }
      result = parts.join(",") + "," + lastThree;
    }

    const prefix = isNegative ? "-Rs. " : "Rs. ";
    return showSymbol ? prefix + result : (isNegative ? "-" : "") + result;
  },

  /**
   * Format date into readable string e.g., '14 Aug 2026'
   */
  formatDate(dateStr) {
    if (!dateStr) return "-";
    try {
      const d = new Date(dateStr);
      if (isNaN(d.getTime())) return dateStr;
      return d.toLocaleDateString("en-GB", {
        day: "2-digit",
        month: "short",
        year: "numeric"
      });
    } catch {
      return dateStr;
    }
  },

  /**
   * Format date with time e.g., '14 Aug 2026, 09:30 AM'
   */
  formatDateTime(dateStr) {
    if (!dateStr) return "-";
    try {
      const d = new Date(dateStr);
      if (isNaN(d.getTime())) return dateStr;
      return d.toLocaleDateString("en-GB", {
        day: "2-digit",
        month: "short",
        year: "numeric",
        hour: "2-digit",
        minute: "2-digit"
      });
    } catch {
      return dateStr;
    }
  },

  /**
   * Generate sequential ID with prefix e.g., PRJ-104
   */
  generateId(prefix = "ITEM", existingList = []) {
    let max = 0;
    existingList.forEach((item) => {
      const id = typeof item === "string" ? item : item.id;
      if (id && id.startsWith(prefix + "-")) {
        const numPart = parseInt(id.split("-")[1], 10);
        if (!isNaN(numPart) && numPart > max) {
          max = numPart;
        }
      }
    });
    const next = max + 1;
    return `${prefix}-${next.toString().padStart(3, "0")}`;
  },

  /**
   * Escape HTML to prevent XSS in dynamic rendering
   */
  escapeHtml(str) {
    if (str === null || str === undefined) return "";
    return String(str)
      .replace(/&/g, "&amp;")
      .replace(/</g, "&lt;")
      .replace(/>/g, "&gt;")
      .replace(/"/g, "&quot;")
      .replace(/'/g, "&#039;");
  },

  /**
   * Status Badge renderer with color mapping
   */
  renderStatusBadge(status) {
    if (!status) return '<span class="badge badge-neutral">-</span>';
    const s = String(status).toLowerCase();

    let variant = "badge-neutral";
    if (["active", "completed", "passed", "delivered", "accepted", "handed over", "paid", "on track"].includes(s)) {
      variant = "badge-success";
    } else if (["in progress", "in production", "sent", "contacted", "finishing & qc", "in transit"].includes(s)) {
      variant = "badge-primary";
    } else if (["pending", "due", "site visit required", "quotation preparation", "negotiation", "attention needed", "partial delivery", "partially paid"].includes(s)) {
      variant = "badge-warning";
    } else if (["failed", "lost", "cancelled", "overdue", "re-inspection required", "delayed"].includes(s)) {
      variant = "badge-danger";
    }

    return `<span class="badge ${variant}"><span class="badge-dot"></span>${this.escapeHtml(status)}</span>`;
  },

  /**
   * Render HTML Progress Bar
   */
  renderProgressBar(percent, showText = true) {
    const val = Math.min(100, Math.max(0, Math.round(Number(percent) || 0)));
    let colorClass = "";
    if (val === 100) colorClass = "success";
    else if (val < 40) colorClass = "warning";

    return `
      <div style="display:flex; align-items:center; gap:8px; width:100%;">
        <div class="progress-bar-container" style="flex:1;">
          <div class="progress-bar-fill ${colorClass}" style="width: ${val}%;"></div>
        </div>
        ${showText ? `<span style="font-size:12px; font-weight:500; min-width:32px; text-align:right;">${val}%</span>` : ""}
      </div>
    `;
  },

  /**
   * Export Array of Objects to CSV
   */
  exportToCsv(filename, rows) {
    if (!rows || !rows.length) {
      alert("No data available to export.");
      return;
    }
    const separator = ",";
    const keys = Object.keys(rows[0]);
    const csvContent =
      keys.join(separator) +
      "\n" +
      rows
        .map((row) => {
          return keys
            .map((k) => {
              let cell = row[k] === null || row[k] === undefined ? "" : row[k];
              cell = cell instanceof Date ? cell.toLocaleString() : cell.toString().replace(/"/g, '""');
              if (cell.search(/("|,|\n)/g) >= 0) {
                cell = `"${cell}"`;
              }
              return cell;
            })
            .join(separator);
        })
        .join("\n");

    const blob = new Blob([csvContent], { type: "text/csv;charset=utf-8;" });
    const link = document.createElement("a");
    if (link.download !== undefined) {
      const url = URL.createObjectURL(blob);
      link.setAttribute("href", url);
      link.setAttribute("download", `${filename}.csv`);
      link.style.visibility = "hidden";
      document.body.appendChild(link);
      link.click();
      document.body.removeChild(link);
    }
  },

